import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
// Same detector as the static script. Only read-only messaging is activated.
export function buildCheckoutObserver(source) {
  const flag = 'const CHECKOUT_OBSERVATION_ONLY = false'
  if (source.split(flag).length !== 2) throw Error('OBSERVER_MODE_SOURCE_INVALID')
  return `// Generated by tools/build-luna-checkout-observer.mjs; do not edit.\n(() => {\ntry { if (globalThis.__lunaCheckoutObserverV1?.alive()) return } catch {}\n${source.replace(flag, 'const CHECKOUT_OBSERVATION_ONLY = true')}\nglobalThis.__lunaCheckoutObserverV1 = { alive: () => Boolean(chrome.runtime.id && chrome.runtime.getManifest().version) }\n})();\n`
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const dir = new URL('./browser-extensions/luna-shipping-capture/', import.meta.url)
  writeFileSync(new URL('checkout-observation.js', dir), buildCheckoutObserver(readFileSync(new URL('content.js', dir), 'utf8')))
}
